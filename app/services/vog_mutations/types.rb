# frozen_string_literal: true

module VOGMutations
  # Types for working with mutation operations, contracts, etc.
  module Types
    include Dry.Types

    # A valid argument key for a mutation
    ArgKey = Coercible::Symbol.constrained(format: /\A[a-z][a-z0-9_]+\z/)

    # A valid authorization predicate method name. Must end with a `?`. Intended
    # for integration with ActionPolicy policies.
    #
    # @see VOGMutations::Implementation.authorizes!
    AuthPredicate = Coercible::Symbol.constrained(format: /\A[a-z][a-z0-9_]+\?\z/)

    # A callable object, such as a Proc, block, or lambda.
    Callable = Types.Interface(:call)

    # The "verb" the contract does
    ContractVerb = Coercible::Symbol.enum(:create, :update, :destroy, :mutate).fallback(:mutate)

    # A hash-like context object with indifferent access.
    LocalContext = Types::Hash.constructor(&:with_indifferent_access)

    # An operation name for identifying mutation operations.
    OperationName = Coercible::String.constrained(filled: true)

    # A GraphQL query with no schema, for building query contexts.
    #
    # @api private
    NULL_QUERY = GraphQL::Query.new(::GraphQL::Schema)

    # A builder for a null query context.
    # It accepts a hash of values to set and produces a `GraphQL::Query::Context`.
    #
    # @api private
    BUILD_NULL_CONTEXT = proc do |**values|
      GraphQL::Query::Context.new(query: NULL_QUERY, values:)
    end

    # A GraphQL query context.
    #
    # It will fallback to a null context generated by {BUILD_NULL_CONTEXT} if none is provided.
    QueryContext = Instance(::GraphQL::Query::Context).default { BUILD_NULL_CONTEXT.() }

    # A mapping of shared arguments used within {VOGMutations::Arguments::SharedSet}s.
    SharedArgumentSetMapping = Hash.map(ArgKey, Any)

    # A module that defines a set of shared arguments for mutations.
    SharedArgumentSet = Instance(::Module)

    # An array of shared argument sets.
    SharedArgumentSets = Array.of(SharedArgumentSet)
  end
end
